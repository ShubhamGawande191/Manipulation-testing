# ruff: noqa: E501  (the MJCF template is clearer unwrapped)
"""Bench scene generator: table, overhead column + workspace camera, leader arm as an obstacle.

    uv run scene build      # config/scene_bench.yaml -> sim/assets/so101/scene_bench.xml
    uv run scene render     # workspace-camera view of the sim scene -> runs/scene/sim_workspace.png

The leader is the stock SO-101 geometry posed at its stow (or rest) pose from
``config/leader_stow.yaml``. Every geom of the stock arm is evaluated by FK and written out as
a static geom under a ``leader`` body. It's an exact-shape obstacle with no joints or actuators,
so the follower model's qpos/ctrl layout is unchanged. Leader LeRobot degrees map to sim radians
with sign +1 / offset 0 (both arms calibrated to the same frame; teleop 1:1).
"""

from __future__ import annotations

from pathlib import Path

import mujoco
import numpy as np
import typer
import yaml

from robot_manipulator.sim.model import ASSET_DIR, JOINTS, joint_qpos_adr, load_model

REPO = Path(__file__).resolve().parents[3]
CONFIG = REPO / "config" / "scene_bench.yaml"
OUT = ASSET_DIR / "scene_bench.xml"
EXTRINSICS = REPO / "config" / "extrinsics" / "workspace.yaml"
app = typer.Typer(add_completion=False, help=__doc__)


def _q(arr) -> str:
    return " ".join(f"{v:.6g}" for v in arr)


def leader_geoms(pose_deg: np.ndarray) -> list[str]:
    """Static <geom> lines for the stock arm posed at ``pose_deg`` (body frame = leader base)."""
    m = load_model("scene.xml")  # stock arm (leader-like links; jaw instead of handle)
    d = mujoco.MjData(m)
    q = np.radians(np.asarray(pose_deg[:5], dtype=float))
    d.qpos[joint_qpos_adr(m, JOINTS)[:5]] = q
    mujoco.mj_forward(m, d)
    lines = []
    for g in range(m.ngeom):
        if m.geom_bodyid[g] == 0:  # world (floor)
            continue
        quat = np.zeros(4)
        mujoco.mju_mat2Quat(quat, d.geom_xmat[g])
        common = f'pos="{_q(d.geom_xpos[g])}" quat="{_q(quat)}" contype="1" conaffinity="1"'
        gtype = m.geom_type[g]
        if gtype == mujoco.mjtGeom.mjGEOM_MESH:
            mesh = m.mesh(m.geom_dataid[g]).name
            lines.append(
                f'<geom type="mesh" mesh="{mesh}" {common} group="2" rgba="0.25 0.55 0.95 1" '
                f'contype="0" conaffinity="0"/>'.replace(' contype="1" conaffinity="1"', "", 1)
            )
        else:
            names = {
                mujoco.mjtGeom.mjGEOM_BOX: "box",
                mujoco.mjtGeom.mjGEOM_SPHERE: "sphere",
                mujoco.mjtGeom.mjGEOM_CAPSULE: "capsule",
                mujoco.mjtGeom.mjGEOM_CYLINDER: "cylinder",
            }
            if gtype not in names:
                continue
            lines.append(
                f'<geom type="{names[gtype]}" size="{_q(m.geom_size[g])}" {common} '
                f'group="3" rgba="0.2 0.4 0.9 0.4"/>'
            )
    return lines


def build(cfg_path: Path = CONFIG, out: Path = OUT, extrinsics: Path | None = EXTRINSICS) -> Path:
    """Write the bench MJCF. The workspace camera pose comes from ``extrinsics`` when that file
    exists (calibrated), else from the placeholder in ``cfg_path``."""
    cfg = yaml.safe_load(Path(cfg_path).read_text())
    t, c, cam, ld = cfg["table"], cfg["column"], cfg["workspace_camera"], cfg["leader"]
    if extrinsics is not None and Path(extrinsics).exists():  # `uv run camcal-extrinsics` output
        cam = {**cam, **yaml.safe_load(Path(extrinsics).read_text())}
    stow = yaml.safe_load((REPO / "config" / "leader_stow.yaml").read_text())
    if ld["pose"] == "stow" and stow.get("stow_pose_deg") is not None:
        pose = np.asarray(stow["stow_pose_deg"], dtype=float)
    else:
        pose = np.asarray(stow["rest_pose_deg"], dtype=float)
    thick = 0.02
    tcx = t["back_edge_x"] + t["size_x"] / 2
    tcy = t["right_edge_y"] + t["size_y"] / 2
    top = t["top_z"]
    col_h = c["lens_height_above_table"]
    col_top = top + col_h
    if cam.get("pos") is not None and cam.get("xyaxes") is not None:
        cam_pos = cam["pos"]  # calibrated: `uv run camcal-extrinsics`
        xy = _q(cam["xyaxes"])
    else:  # placeholder: straight down, image "up" = +x (toward the table front)
        cam_pos = (c["center_x"] + cam["overhang_x"], c["center_y"], col_top - 0.01)
        pitch = np.radians(cam["pitch_deg"])
        xy = f"0 -1 0 {np.cos(pitch):.6f} 0 {np.sin(pitch):.6f}"
    leader = "\n      ".join(leader_geoms(pose))
    xml = f"""<mujoco model="so101_pinc_bench">
  <!-- GENERATED by `uv run scene build` from config/scene_bench.yaml; do not edit by hand. -->
  <include file="so101_pinc.xml"/>
  <visual>
    <headlight diffuse="0.6 0.6 0.6" ambient="0.3 0.3 0.3" specular="0 0 0"/>
    <global azimuth="160" elevation="-25" offwidth="1280" offheight="960"/>
  </visual>
  <asset>
    <texture type="skybox" builtin="gradient" rgb1="0.35 0.3 0.25" rgb2="0.1 0.08 0.06" width="512" height="3072"/>
    <material name="table" rgba="0.93 0.93 0.91 1"/>
    <material name="floor" rgba="0.55 0.38 0.22 1"/>
    <material name="column" rgba="0.08 0.08 0.08 1"/>
  </asset>
  <worldbody>
    <light pos="0 0 2.5" dir="0 0 -1" directional="true" diffuse="0.7 0.7 0.7"/>
    <geom name="room_floor" type="plane" size="0 0 0.05" pos="0 0 {top - 0.45:.4f}" material="floor"/>
    <geom name="table" type="box" size="{t["size_x"] / 2:.4f} {t["size_y"] / 2:.4f} {thick / 2:.4f}"
      pos="{tcx:.4f} {tcy:.4f} {top - thick / 2:.4f}" material="table"/>
    <geom name="column" type="box" size="{c["size_x"] / 2:.4f} {c["size_y"] / 2:.4f} {col_h / 2:.4f}"
      pos="{c["center_x"]:.4f} {c["center_y"]:.4f} {top + col_h / 2:.4f}" material="column"/>
    <geom name="camera_arm" type="box" size="{cam["overhang_x"] / 2 + 0.013:.4f} 0.013 0.012"
      pos="{c["center_x"] + cam["overhang_x"] / 2:.4f} {c["center_y"]:.4f} {col_top - 0.012:.4f}"
      material="column"/>
    <camera name="workspace_cam" mode="fixed" pos="{_q(cam_pos)}" xyaxes="{xy}" fovy="{cam["fovy_deg"]}"/>
    <body name="leader" pos="{ld["base_x"]:.4f} {ld["base_y"]:.4f} 0">
      {leader}
    </body>
  </worldbody>
</mujoco>
"""
    out.write_text(xml)
    return out


@app.command("build")
def build_cmd() -> None:
    """Write sim/assets/so101/scene_bench.xml from config/scene_bench.yaml."""
    path = build()
    m = load_model(path.name)
    typer.echo(f"-> {path}  (nbody {m.nbody}, ngeom {m.ngeom}, nu {m.nu})")


@app.command()
def render(width: int = 640, height: int = 480) -> None:
    """Render the sim workspace-camera view (to compare with `uv run cam-setup --snapshot`)."""
    import cv2

    m = load_model(OUT.name)
    d = mujoco.MjData(m)
    d.qpos[joint_qpos_adr(m, JOINTS)[:5]] = np.radians([-3.3, -102.8, 96.1, 78.2, -85.0])
    mujoco.mj_forward(m, d)
    r = mujoco.Renderer(m, height, width)
    r.update_scene(d, camera="workspace_cam")
    out = REPO / "runs" / "scene" / "sim_workspace.png"
    out.parent.mkdir(parents=True, exist_ok=True)
    cv2.imwrite(str(out), cv2.cvtColor(r.render(), cv2.COLOR_RGB2BGR))
    typer.echo(f"-> {out}")


if __name__ == "__main__":
    app()
